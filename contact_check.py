"""
Checking for unverified emails and links in text.
Any email or link generated by the model must have evidence in a real source, and if the company's official website is known, it must be on the same domain.
"""

import re
from urllib.parse import urlparse

_PATTERN = re.compile(r"https?://[^\s)\]>\"']+|[\w.+-]+@[\w-]+(?:\.[\w-]+)+")


def official_domain(website: str) -> str:
    # Returns the domain from the official company website URL.
    website = website.strip()
    if not website:
        return ""
    if "//" not in website:
        website = "https://" + website
    return urlparse(website).netloc.lower().split(":")[0].removeprefix("www.")


def _clean(value: str) -> str:
    return value.rstrip(".,;:!").rstrip("/").lower()


def _host(value: str) -> str:
    if "@" in value and not value.lower().startswith("http"):
        return value.rsplit("@", 1)[1].lower()
    return urlparse(value).netloc.lower().split(":")[0].removeprefix("www.")


def _on_domain(value: str, domain: str) -> bool:
    host = _host(value)
    return host == domain or host.endswith("." + domain)


def find_unverified_contacts(
    text: str, evidence: str, official_domain: str = "", trusted: str = ""
) -> list[str]:
    evidence = evidence.lower()
    trusted = trusted.lower()
    found = []
    for match in _PATTERN.finditer(text):
        value = match.group(0).rstrip(".,;:!")
        key = _clean(value)
        if key in trusted:
            continue
        verified = key in evidence and (not official_domain or _on_domain(value, official_domain))
        if not verified and value not in found:
            found.append(value)
    return found


def strip_unverified_contacts(
    text: str, evidence: str, official_domain: str = "", trusted: str = ""
) -> str:
    bad = find_unverified_contacts(text, evidence, official_domain, trusted)
    for value in bad:
        text = text.replace(value, "")
    if bad:
        text += "\nApplication contact: No verified application contact found."
    return text